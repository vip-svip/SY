'use strict';
const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const source = fs.readFileSync(process.argv[2], 'utf8');
const marker = '\ntry {\n  var file = (typeof scriptArgs';
const cut = source.indexOf(marker);
assert(cut > 0, 'CLI entrypoint marker found');
const context = {};
vm.runInNewContext(source.slice(0, cut) + '\nthis.convertForTest = convert;\n', context);
const convert = context.convertForTest;
let out = convert({type:'vless', tag:'v6 node', server:'2001:db8::1', server_port:443, uuid:'id', tls:{enabled:true}});
assert(out.startsWith('vless://id@[2001:db8::1]:443?security=tls'), out);
out = convert({type:'trojan', tag:'auth', server:'2001:db8::2', server_port:443, password:'p@ss', tls:{enabled:true}});
assert(out.startsWith('trojan://p%40ss@[2001:db8::2]:443'), out);
out = convert({type:'vless', tag:'reality', server:'edge.example', server_port:443, uuid:'id', tls:{enabled:true, reality:{public_key:'pub', short_id:'12ab'}}});
assert(out.includes('?security=reality&'), out);
assert(out.includes('&pbk=pub&sid=12ab'), out);
out = convert({type:'vless', tag:'ws', server:'edge.example', server_port:443, uuid:'id', tls:{enabled:true}, transport:{type:'ws',path:'/a b?c',headers:{Host:'cdn.example'}}});
assert(out.includes('&type=ws&path=%2Fa%20b%3Fc&host=cdn.example'), out);
assert.strictEqual(convert({type:'vless',server:'edge.example',server_port:70000,uuid:'id'}), '');
assert.strictEqual(convert({type:'vless',server:'edge.example',server_port:443.5,uuid:'id'}), '');
console.log('PASS: sing-box JSON URI IPv6, reality, transport, and port validation');
