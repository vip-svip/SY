'use strict';
const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const source = fs.readFileSync(process.argv[2], 'utf8');
const marker = '\ntry {\n  var file = (typeof scriptArgs';
const cut = source.indexOf(marker);
assert(cut > 0, 'CLI entrypoint marker found');
const context = {};
vm.runInNewContext(source.slice(0, cut) + '\nthis.convertForTest = convert;\n', context);
const convert = context.convertForTest;
const base = {type:'vless', tag:'reality', server:'edge.example', server_port:443, uuid:'id'};
assert.strictEqual(convert({...base, tls:{enabled:true, reality:{short_id:'12ab'}}}), '', 'short_id without public_key must be rejected');
assert.strictEqual(convert({...base, tls:{enabled:false, reality:{public_key:'pub', short_id:'12ab'}}}), '', 'Reality while TLS is disabled must be rejected');
const good = convert({...base, tls:{enabled:true, reality:{public_key:'pub', short_id:'12ab'}}});
assert(good.includes('?security=reality&'), good);
assert(good.includes('&pbk=pub&sid=12ab'), good);
assert.strictEqual(convert({...base, tls:{enabled:true, reality:{public_key:'pub'}}}).includes('security=reality'), true);
console.log('PASS: sing-box VLESS Reality requires TLS enabled and public key');
