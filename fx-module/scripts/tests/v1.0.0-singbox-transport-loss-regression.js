'use strict';
const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const source = fs.readFileSync(process.argv[2], 'utf8');
const marker = '\ntry {\n  var file = (typeof scriptArgs';
const cut = source.indexOf(marker);
assert(cut > 0, 'CLI entrypoint marker found');
const context = {};
vm.runInNewContext(source.slice(0, cut) + '\nthis.convertForTest = convert;\n', context);
const convert = context.convertForTest;
const base = {server:'edge.example', server_port:443, tag:'transport-test'};
assert.strictEqual(convert({...base, type:'vless', uuid:'id', transport:{type:'grpc', service_name:'svc'}}), '', 'VLESS gRPC must not be silently downgraded to TCP');
assert.strictEqual(convert({...base, type:'vless', uuid:'id', transport:{type:'httpupgrade', path:'/x'}}), '', 'VLESS HTTPUpgrade must not be dropped');
assert.strictEqual(convert({...base, type:'trojan', password:'pw', transport:{type:'ws', path:'/x'}}), '', 'unsupported Trojan WS must not be dropped');
assert.strictEqual(convert({...base, type:'shadowsocks', method:'aes-128-gcm', password:'pw', transport:{type:'ws'}}), '', 'unsupported Shadowsocks transport must not be dropped');
assert(convert({...base, type:'vless', uuid:'id'}).startsWith('vless://'), 'plain TCP VLESS remains supported');
assert(convert({...base, type:'vless', uuid:'id', transport:{type:'ws', path:'/ws', headers:{Host:'cdn.example'}}}).includes('type=ws'), 'VLESS WebSocket remains supported');
assert(convert({...base, type:'vmess', uuid:'id', tls:{enabled:true, server_name:'sni.example'}}).startsWith('vmess://'), 'VMess TLS remains supported');
const vmessUri = convert({...base, type:'vmess', uuid:'id', tls:{enabled:true, server_name:'sni.example'}});
const payload = JSON.parse(Buffer.from(vmessUri.slice(8), 'base64').toString('utf8'));
assert.strictEqual(payload.sni, 'sni.example', 'VMess SNI is preserved in JSON payload');
console.log('PASS: unsupported sing-box transports are rejected instead of silently lost');
