#!/system/bin/sh
set -eu
ROOT=$(CDPATH= cd -- "$(dirname "$0")/../.." && pwd)
H="$ROOT/webroot/index.html"
S="$ROOT/scripts/vpnsub.sh"
F="$ROOT/scripts/subfetch.sh"
J="$ROOT/scripts/vpn-singbox-json.js"
T=$(mktemp -d "${TMPDIR:-/tmp}/fx-vpn-sub-import.XXXXXX")
trap 'rm -rf "$T"' EXIT HUP INT TERM
# Frontend import must force a refresh, validate the entire cached body, and surface useful errors.
grep -Fq 'return subMeta(url,true)' "$H"
grep -Fq 'subReadAll(m.key,8388608,size)' "$H"
grep -Fq '订阅正文长度不一致' "$H"
grep -Fq '服务器返回了网页/登录验证页' "$H"
grep -Fq 'parseSingBoxJSON(decoded)' "$H"
# Backend supports BOM/CRLF and base64-wrapped Clash YAML; test actual conversion without network.
MODDIR="$ROOT"; PG="$T/state"; export MODDIR PG
mkdir -p "$PG/cache"
. "$S"
printf '\357\273\277# generated by provider\r\nproxies:\r\n  - name: Tokyo\r\n    type: vless\r\n    server: edge.example.com\r\n    port: 443\r\n    uuid: 123e4567-e89b-12d3-a456-426614174000\r\n    tls: true\r\n' > "$T/clash.yaml"
vpn_yaml_to_uri "$T/clash.yaml" > "$T/raw.out"
grep -q '^vless://123e4567-e89b-12d3-a456-426614174000@edge.example.com:443' "$T/raw.out"
base64 "$T/clash.yaml" > "$T/clash.b64"
base64 -d "$T/clash.b64" > "$T/decoded.yaml"
vpn_yaml_to_uri "$T/decoded.yaml" > "$T/base64.out"
grep -q '^vless://123e4567-e89b-12d3-a456-426614174000@edge.example.com:443' "$T/base64.out"
# The JSON converter must be wired to the bundled QuickJS engine and syntax-valid JS.
grep -Fq 'vpn_singbox_json_to_uri "$_vs_f"' "$S"
grep -Fq 'vpn_singbox_json_to_uri "$_vs_dec"' "$S"
grep -Fq 'outbounds' "$J"
sh -n "$S"
sh -n "$F"
# Missing QuickJS must be reported as a conversion failure (not silently return success).
mkdir -p "$T/no-qjs/scripts" "$T/no-qjs-state"
cp "$J" "$T/no-qjs/scripts/vpn-singbox-json.js"
: > "$T/no-qjs-state/apply.log"
_old_moddir=$MODDIR
_old_pg=$PG
pg_log() { echo "$*" >> "$PG/apply.log"; }
MODDIR="$T/no-qjs"; PG="$T/no-qjs-state"
if vpn_singbox_json_to_uri "$T/clash.yaml" >/dev/null 2>&1; then
  echo 'expected missing QuickJS to return failure' >&2
  exit 1
fi
MODDIR=$_old_moddir; PG=$_old_pg
grep -q 'sing-box JSON parser unavailable' "$T/no-qjs-state/apply.log"
# Regression guard: cache directory setup must occur before truncating the aggregate file.
_mkdir_line=$(grep -n 'mkdir -p "$PG/cache"' "$S" | head -n 1 | cut -d: -f1)
_init_line=$(grep -n ': > "$_vs_all"' "$S" | head -n 1 | cut -d: -f1)
[ -n "$_mkdir_line" ] && [ -n "$_init_line" ] && [ "$_mkdir_line" -lt "$_init_line" ]
# Mixed success/failure must be surfaced as partial update, not a plain success log.
grep -Fq '_vs_fetch_fail=$((_vs_fetch_fail + 1))' "$S"
grep -Fq '订阅部分更新：成功拉取' "$S"
# The no-anchor append path must build a candidate and pass the same safety validator.
grep -Fq 'cat "$CONF" && printf' "$S"
grep -Fq '_vs_write "$CONF.new"' "$S"
# Configuration backup must succeed before replacement; selection changes must be deferred
# until after the node-list write so a failed write cannot leave a dangling selection.
grep -Fq 'if ! _vs_backup; then' "$S"
grep -Fq 'settings.conf 备份失败；拒绝覆盖原配置' "$S"
# A smaller but valid new node list must not be rejected merely because the whole
# settings.conf shrinks; preserve and compare all non-empty non-node config lines.
if grep -Fq '原来的 80%' "$S"; then
  echo 'whole-file 80% size guard can reject legitimate smaller subscriptions' >&2
  exit 1
fi
grep -Fq 'cmp -s "$_v_old_rest" "$_v_new_rest"' "$S"
# If persisting the default selected node fails after the list commit, the prior
# settings.conf must be restored atomically from the backup made for this update.
grep -Fq 'cp -p "$_bk" "$_vs_restore_tmp"' "$S"
grep -Fq 'mv "$_vs_restore_tmp" "$CONF"' "$S"
grep -Fq '已恢复原 settings.conf' "$S"
grep -Fq '非节点配置发生变化或疑似截断' "$S"
# If an existing node section cannot be safely rewritten, abort instead of inserting a duplicate section.
grep -Fq '_vs_had_node_section=0' "$S"
grep -Fq '_vs_had_node_section=1' "$S"
grep -Fq '为避免重复 [list:vpn_node] 段，已保留原配置并中止更新' "$S"
_abort_line=$(grep -n 'if [ "$_vs_had_node_section" = 1 ]; then' "$S" | head -n 1 | cut -d: -f1)
_insert_line=$(grep -n '段不存在（首次导入）：改成' "$S" | head -n 1 | cut -d: -f1)
[ -n "$_abort_line" ] && [ -n "$_insert_line" ] && [ "$_abort_line" -lt "$_insert_line" ]
_write_line=$(grep -n 'if ! _vs_write "$CONF.new"; then' "$S" | head -n 1 | cut -d: -f1)
_select_line=$(grep -n 'if pg_set vpn_node "$_vs_first"; then' "$S" | head -n 1 | cut -d: -f1)
[ -n "$_write_line" ] && [ -n "$_select_line" ] && [ "$_write_line" -lt "$_select_line" ]
if grep -Fq 'printf \\n >> "$CONF"' "$S"; then
  echo 'unsafe direct append to settings.conf remains' >&2
  exit 1
fi
if command -v node >/dev/null 2>&1; then node --check "$J"; fi
echo 'FX VPN subscription import regression: PASS'
