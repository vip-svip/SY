#!/bin/sh
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
ACTIVITY="$ROOT/adhook/app/src/main/java/de/privacyguard/adhook/imported/dia/FxDiaFridaActivity.java"
EVENTS="$ROOT/adhook/app/src/main/java/de/privacyguard/adhook/imported/dia/FxDiaMonitorEventsActivity.java"
SESSION="$ROOT/adhook/app/src/main/java/de/privacyguard/adhook/imported/dia/FxDiaSessionLogActivity.java"
MANIFEST="$ROOT/adhook/app/src/main/AndroidManifest.xml"
PARSER="$ROOT/adhook/app/src/main/java/de/privacyguard/adhook/imported/dia/FxDiaMonitorEventParser.java"
UNIT="$ROOT/adhook/app/src/test/java/de/privacyguard/adhook/imported/dia/FxDiaMonitorEventParserTest.java"
HOST_TEST="$ROOT/scripts/tests/FxDiaMonitorEventParserHostTest.java"
AUTO_CLICK="$ROOT/adhook/app/src/main/assets/dia/fx_auto_click_template.js"
DIALOG_REMOVE="$ROOT/adhook/app/src/main/assets/dia/fx_dialog_remove_template.js"
fail(){ echo "FAIL: $*" >&2; exit 1; }
[ -s "$ACTIVITY" ] && [ -s "$EVENTS" ] && [ -s "$SESSION" ] && [ -s "$PARSER" ] && [ -s "$UNIT" ] || fail "Dia monitor-event sources missing"
[ -s "$AUTO_CLICK" ] || fail "Dia automatic-click template asset missing"
[ -s "$DIALOG_REMOVE" ] || fail "Dia dialog-removal template asset missing"
grep -Fq 'button("查看结构化监控事件", () -> showMonitorEvents())' "$ACTIVITY" || fail "Frida screen has no native monitor-event browser"
grep -Fq 'new Intent(this, FxDiaMonitorEventsActivity.class)' "$ACTIVITY" || fail "Frida page does not route to the native event Activity"
grep -Fq 'tail -n 800' "$EVENTS" || fail "monitor-event reader is not bounded at the source"
for directory in /data /data/adb /data/adb/privacyguard /data/adb/privacyguard/dia-frida /data/adb/privacyguard/dia-frida/logs; do
  grep -Fq "$directory" "$EVENTS" || fail "monitor-event reader does not validate parent directory: $directory"
done
grep -Fq 'FX_DIA_LOG_PATH_UNTRUSTED' "$EVENTS" || fail "monitor-event reader does not reject symlinked log paths"
grep -Fq 'if [ -L' "$EVENTS" || fail "monitor-event reader does not reject symlinked parent directories"
grep -Fq 'MAX_EVENTS = 300' "$PARSER" || fail "monitor-event parser has no event-count bound"
grep -Fq 'MAX_LOG_CHARS = 256 * 1024' "$PARSER" || fail "monitor-event parser has no input-size bound"
grep -Fq 'case "SQL":' "$PARSER" || fail "SQL monitor family is not supported"
grep -Fq 'case "HTTP":' "$PARSER" || fail "HTTP monitor family is not supported"
grep -Fq 'case "RUNTIME":' "$PARSER" || fail "Runtime monitor family is not supported"
grep -Fq 'case "APPENTRY":' "$PARSER" || fail "Activity-entry observer events are discarded"
grep -Fq 'return "Activity 入口";' "$PARSER" || fail "Activity-entry event category is missing"
grep -Fq '[DIA_APPENTRY]' "$UNIT" || fail "Activity-entry parser fixture is missing"
grep -Fq 'containsKey("extras")' "$UNIT" || fail "Intent extras privacy assertion is missing"
grep -Fq 'containsKey("data")' "$UNIT" || fail "Intent URI/data privacy assertion is missing"
grep -Fq 'containsKey("component")' "$UNIT" || fail "Intent component privacy assertion is missing"
grep -Fq 'case "click-auto":' "$ACTIVITY" || fail "Frida activity cannot load the auto-click template"
grep -Fq '按文本/ID 自动点击' "$ACTIVITY" || fail "auto-click page does not load its template"
# Frida tools are hosted in the imported Dia Frida Activity, not MainActivity.
grep -Fq 'KEYWORD_PATTERNS = [];' "$AUTO_CLICK" || fail "auto-click must default to no regex rules"
grep -Fq 'VIEW_IDS = [];' "$AUTO_CLICK" || fail "auto-click must default to no ID rules"
grep -Fq 'MAX_TREE_NODES = 1500;' "$AUTO_CLICK" || fail "auto-click tree size must be bounded"
grep -Fq 'MAX_TREE_DEPTH = 28;' "$AUTO_CLICK" || fail "auto-click tree depth must be bounded"
grep -Fq 'MAX_CLICKS_PER_PROCESS = 8;' "$AUTO_CLICK" || fail "auto-click count must be bounded"
grep -Fq 'retained.performClick()' "$AUTO_CLICK" || fail "auto-click action missing"
grep -Fq 'Java.scheduleOnMainThread' "$AUTO_CLICK" || fail "auto-click must execute on UI thread"
grep -Fq 'isShown()' "$AUTO_CLICK" || fail "auto-click must recheck visibility"
grep -Fq 'MAX_TREE_NODES - visited - waiting' "$AUTO_CLICK" || fail "auto-click pending queue is not bounded"
grep -Fq 'case "viewgroup-remove":' "$ACTIVITY" || fail "Frida activity cannot load the dialog-removal template"
grep -Fq '按文本/ID 移除匹配弹窗' "$ACTIVITY" || fail "dialog-removal page does not load its template"
# Both templates are reachable through the Frida Activity native controls and route cases.
grep -Fq 'ALERT_KEYWORD_PATTERNS = [];' "$DIALOG_REMOVE" || fail "dialog-removal must default to no text rules"
grep -Fq 'ALERT_VIEW_IDS = [];' "$DIALOG_REMOVE" || fail "dialog-removal must default to no ID rules"
grep -Fq 'ALLOW_ANY_PARENT = false;' "$DIALOG_REMOVE" || fail "dialog-removal must default to root-only scope"
grep -Fq '0x01020002' "$DIALOG_REMOVE" || fail "dialog-removal must recognize android.R.id.content"
grep -Fq 'parent.removeView(child)' "$DIALOG_REMOVE" || fail "dialog-removal action missing"
grep -Fq 'MAX_TREE_NODES = 1500;' "$DIALOG_REMOVE" || fail "dialog-removal tree bound missing"
grep -Fq 'MAX_TREE_DEPTH = 28;' "$DIALOG_REMOVE" || fail "dialog-removal depth bound missing"
grep -Fq 'MAX_REMOVE_PER_PROCESS = 5;' "$DIALOG_REMOVE" || fail "dialog-removal count bound missing"
grep -Fq 'MAX_RECHECKS = 8;' "$DIALOG_REMOVE" || fail "dialog-removal retry bound missing"
grep -Fq 'MAX_PENDING_ROOTS = 64;' "$DIALOG_REMOVE" || fail "dialog-removal pending bound missing"
grep -Fq 'Java.scheduleOnMainThread' "$DIALOG_REMOVE" || fail "dialog-removal must mutate views on the main thread"
grep -Fq 'function eligibleParent(parent)' "$DIALOG_REMOVE" || fail "dialog-removal immediate-parent scope missing"
! grep -Fq 'resolveRoot(' "$DIALOG_REMOVE" || fail "dialog-removal must not climb and remove whole content trees"
command -v node >/dev/null 2>&1 || fail "Node.js is required to syntax-check Dia Frida templates"
node --check "$AUTO_CLICK" || fail "auto-click template JavaScript syntax invalid"
node --check "$DIALOG_REMOVE" || fail "dialog-removal template JavaScript syntax invalid"
command -v node >/dev/null 2>&1 || fail "Node.js is required to syntax-check Dia Frida templates"
node --check "$AUTO_CLICK" || fail "auto-click template JavaScript syntax invalid"
[ -s "$HOST_TEST" ] || fail "standalone Activity-entry parser host test is missing"
grep -Fq 'SQL 文本' "$EVENTS" || fail "event view does not explain content redaction"
grep -Fq 'private void showMonitorEvents()' "$ACTIVITY" || fail "Frida page event route missing"
grep -Fq 'new Intent(this, FxDiaMonitorEventsActivity.class)' "$ACTIVITY" || fail "Frida event route target mismatch"
grep -Fq 'matched > shown' "$EVENTS" || fail "event view row cap missing"
grep -Fq 'private int loadGeneration;' "$EVENTS" || fail "event generation guard missing"
grep -Fq 'final int request = ++loadGeneration;' "$EVENTS" || fail "event request generation missing"
grep -Fq 'new ArrayBlockingQueue<>(1)' "$EVENTS" || fail "monitor-event Root read queue must be bounded to one waiter"
grep -Fq 'private void enqueueLatest(Runnable task)' "$EVENTS" || fail "monitor-event refresh must retain only the latest queued request"
grep -Fq 'worker.getQueue().poll();' "$EVENTS" || fail "stale queued Root reads are not discarded"
grep -Fq 'new ThreadPoolExecutor.AbortPolicy()' "$EVENTS" || fail "monitor-event worker must reject work after shutdown"
grep -Fq 'request != loadGeneration' "$EVENTS" || fail "late event results are not discarded"
grep -Fq 'onSaveInstanceState(Bundle outState)' "$EVENTS" || fail "monitor-event filter state is not saved"
grep -Fq 'restoreUiState(state)' "$EVENTS" || fail "monitor-event filter state is not restored"
grep -Fq 'STATE_CATEGORY' "$EVENTS" || fail "monitor-event category selection is not persisted"
grep -Fq 'STATE_AUTO_REFRESH' "$EVENTS" || fail "monitor-event auto-refresh preference is not persisted"
grep -Fq 'STATE_SCROLL_Y' "$EVENTS" || fail "monitor-event scroll position is not persisted"
grep -Fq 'restorePendingScrollPosition()' "$EVENTS" || fail "monitor-event scroll restore hook missing"
grep -Fq 'onSaveInstanceState(Bundle outState)' "$SESSION" || fail "session-log search state is not saved"
grep -Fq 'restoreUiState(state)' "$SESSION" || fail "session-log search state is not restored"
grep -Fq 'STATE_SEARCH' "$SESSION" || fail "session-log search filter is not persisted"
grep -Fq 'STATE_SCROLL_Y' "$SESSION" || fail "session-log scroll position is not persisted"
grep -Fq 'restorePendingScrollPosition()' "$SESSION" || fail "session-log scroll restore hook missing"
grep -Fq 'loadGeneration++;' "$EVENTS" || fail "Activity teardown generation invalidation missing"
grep -Fq 'isSafePackageName(targetPackage)' "$EVENTS" || fail "target package validation missing"
grep -Fq 'if [ -L' "$EVENTS" || fail "symlink log path guard missing"
grep -Fq 'dia-frida/logs/' "$ACTIVITY" || fail "Frida log directory contract missing"
grep -Fq 'dia-frida/logs/' "$EVENTS" || fail "native event page log directory mismatch"
grep -Fq 'private String checkedSessionLogDirectoryPrefix()' "$ACTIVITY" || fail "Frida clear-log action must validate every parent directory"
grep -Fq "[ -L '/data' ]" "$ACTIVITY" || fail "Frida clear-log action must reject a symlinked /data root"
grep -Fq "FX_DIA_LOG_PATH_UNAVAILABLE" "$ACTIVITY" || fail "Frida clear-log action must fail closed when a parent directory is absent or a symlink"
grep -Fq 'String command = checkedSessionLogDirectoryPrefix()' "$ACTIVITY" || fail "Frida clear-log Root command must include the parent-directory guard"
grep -Fq 'FX_DIA_LOG_CLEARED' "$ACTIVITY" || fail "Frida clear-log action must emit a success marker only after truncation and chmod"
grep -Fq 'FX_DIA_LOG_MISSING_OR_UNSAFE' "$ACTIVITY" || fail "Frida clear-log action must reject a missing or symlink target file"
grep -Fq '清空失败，日志未被确认清空' "$ACTIVITY" || fail "Frida clear-log UI must not report success when Root does not confirm truncation"
python3 - "$MANIFEST" <<'PY'
import sys
import xml.etree.ElementTree as ET
root = ET.parse(sys.argv[1]).getroot()
android = "{http://schemas.android.com/apk/res/android}"
entries = [node for node in root.findall("./application/activity")
           if node.attrib.get(android + "name") == ".imported.dia.FxDiaMonitorEventsActivity"]
assert len(entries) == 1, "monitor Activity missing or duplicated"
assert entries[0].attrib.get(android + "exported") == "false", "monitor Activity must be private"
PY
grep -Fq 'isSafeAuthority(value)' "$PARSER" || fail "host/endpoint authority validation missing"
grep -Fq 'URL credentials/path must not be displayed as host' "$HOST_TEST" || fail "network privacy Host test missing"
if ! command -v javac >/dev/null 2>&1 || ! command -v java >/dev/null 2>&1; then
    fail "JDK is required to execute the standalone monitor parser regression"
fi
OUT=$(mktemp -d)
trap 'rm -rf "$OUT"' EXIT HUP INT TERM
javac -Xlint:all -Werror -d "$OUT" "$PARSER" "$HOST_TEST"
java -cp "$OUT" de.privacyguard.adhook.imported.dia.FxDiaMonitorEventParserHostTest
echo "PASS: Dia monitor-event browser is bounded, filterable and metadata-only"
