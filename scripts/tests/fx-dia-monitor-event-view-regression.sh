#!/bin/sh
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
ACTIVITY="$ROOT/adhook/app/src/main/java/de/privacyguard/adhook/imported/dia/FxDiaFridaActivity.java"
PARSER="$ROOT/adhook/app/src/main/java/de/privacyguard/adhook/imported/dia/FxDiaMonitorEventParser.java"
UNIT="$ROOT/adhook/app/src/test/java/de/privacyguard/adhook/imported/dia/FxDiaMonitorEventParserTest.java"
HOST_TEST="$ROOT/scripts/tests/FxDiaMonitorEventParserHostTest.java"
AUTO_CLICK="$ROOT/adhook/app/src/main/assets/dia/fx_auto_click_template.js"
DIALOG_REMOVE="$ROOT/adhook/app/src/main/assets/dia/fx_dialog_remove_template.js"
fail(){ echo "FAIL: $*" >&2; exit 1; }
[ -s "$ACTIVITY" ] && [ -s "$PARSER" ] && [ -s "$UNIT" ] || fail "Dia monitor-event sources missing"
[ -s "$AUTO_CLICK" ] || fail "Dia automatic-click template asset missing"
[ -s "$DIALOG_REMOVE" ] || fail "Dia dialog-removal template asset missing"
grep -Fq 'button("查看结构化监控事件", () -> showMonitorEvents())' "$ACTIVITY" || fail "Frida screen has no native monitor-event browser"
grep -Fq 'tail -n 800' "$ACTIVITY" || fail "monitor-event reader is not bounded at the source"
grep -Fq 'MAX_EVENTS = 300' "$PARSER" || fail "monitor-event parser has no event-count bound"
grep -Fq 'MAX_LOG_CHARS = 256 * 1024' "$PARSER" || fail "monitor-event parser has no input-size bound"
grep -Fq 'case "SQL":' "$PARSER" || fail "SQL monitor family is not supported"
grep -Fq 'case "HTTP":' "$PARSER" || fail "HTTP monitor family is not supported"
grep -Fq 'case "RUNTIME":' "$PARSER" || fail "Runtime monitor family is not supported"
grep -Fq 'case "APPENTRY":' "$PARSER" || fail "Activity-entry observer events are discarded"
grep -Fq 'return "Activity 入口";' "$PARSER" || fail "Activity-entry event category is missing"
grep -Fq '[DIA_APPENTRY]' "$UNIT" || fail "Activity-entry parser fixture is missing"
grep -Fq 'containsKey("extras")' "$UNIT" || fail "Intent extras privacy assertion is missing"
grep -Fq 'containsKey("data")' "$UNIT" || fail "Intent URI/data privacy assertion is missing"
grep -Fq 'containsKey("component")' "$UNIT" || fail "Intent component privacy assertion is missing"
grep -Fq 'case "click-auto":' "$ACTIVITY" || fail "Frida activity cannot load the auto-click template"
grep -Fq '按文本/ID 自动点击' "$ACTIVITY" || fail "auto-click page does not load its template"
grep -Fq '按文本/ID 自动点击' "$ROOT/adhook/app/src/main/java/de/privacyguard/adhook/MainActivity.java" || fail "auto-click page missing from Dia native navigation"
grep -Fq 'KEYWORD_PATTERNS = [];' "$AUTO_CLICK" || fail "auto-click must default to no regex rules"
grep -Fq 'VIEW_IDS = [];' "$AUTO_CLICK" || fail "auto-click must default to no ID rules"
grep -Fq 'MAX_TREE_NODES = 1500;' "$AUTO_CLICK" || fail "auto-click tree size must be bounded"
grep -Fq 'MAX_TREE_DEPTH = 28;' "$AUTO_CLICK" || fail "auto-click tree depth must be bounded"
grep -Fq 'MAX_CLICKS_PER_PROCESS = 8;' "$AUTO_CLICK" || fail "auto-click count must be bounded"
grep -Fq 'retained.performClick()' "$AUTO_CLICK" || fail "auto-click action missing"
grep -Fq 'Java.scheduleOnMainThread' "$AUTO_CLICK" || fail "auto-click must execute on UI thread"
grep -Fq 'isShown()' "$AUTO_CLICK" || fail "auto-click must recheck visibility"
grep -Fq 'MAX_TREE_NODES - visited - waiting' "$AUTO_CLICK" || fail "auto-click pending queue is not bounded"
grep -Fq 'case "viewgroup-remove":' "$ACTIVITY" || fail "Frida activity cannot load the dialog-removal template"
grep -Fq '按文本/ID 移除匹配弹窗' "$ACTIVITY" || fail "dialog-removal page does not load its template"
grep -Fq '按文本/ID 移除匹配弹窗' "$ROOT/adhook/app/src/main/java/de/privacyguard/adhook/MainActivity.java" || fail "dialog-removal page missing from native navigation"
grep -Fq 'ALERT_KEYWORD_PATTERNS = [];' "$DIALOG_REMOVE" || fail "dialog-removal must default to no text rules"
grep -Fq 'ALERT_VIEW_IDS = [];' "$DIALOG_REMOVE" || fail "dialog-removal must default to no ID rules"
grep -Fq 'ALLOW_ANY_PARENT = false;' "$DIALOG_REMOVE" || fail "dialog-removal must default to root-only scope"
grep -Fq '0x01020002' "$DIALOG_REMOVE" || fail "dialog-removal must recognize android.R.id.content"
grep -Fq 'parent.removeView(child)' "$DIALOG_REMOVE" || fail "dialog-removal action missing"
grep -Fq 'MAX_TREE_NODES = 1500;' "$DIALOG_REMOVE" || fail "dialog-removal tree bound missing"
grep -Fq 'MAX_TREE_DEPTH = 28;' "$DIALOG_REMOVE" || fail "dialog-removal depth bound missing"
grep -Fq 'MAX_REMOVE_PER_PROCESS = 5;' "$DIALOG_REMOVE" || fail "dialog-removal count bound missing"
grep -Fq 'MAX_RECHECKS = 8;' "$DIALOG_REMOVE" || fail "dialog-removal retry bound missing"
grep -Fq 'MAX_PENDING_ROOTS = 64;' "$DIALOG_REMOVE" || fail "dialog-removal pending bound missing"
grep -Fq 'Java.scheduleOnMainThread' "$DIALOG_REMOVE" || fail "dialog-removal must mutate views on the main thread"
grep -Fq 'function eligibleParent(parent)' "$DIALOG_REMOVE" || fail "dialog-removal immediate-parent scope missing"
! grep -Fq 'resolveRoot(' "$DIALOG_REMOVE" || fail "dialog-removal must not climb and remove whole content trees"
command -v node >/dev/null 2>&1 || fail "Node.js is required to syntax-check Dia Frida templates"
node --check "$AUTO_CLICK" || fail "auto-click template JavaScript syntax invalid"
node --check "$DIALOG_REMOVE" || fail "dialog-removal template JavaScript syntax invalid"
command -v node >/dev/null 2>&1 || fail "Node.js is required to syntax-check Dia Frida templates"
node --check "$AUTO_CLICK" || fail "auto-click template JavaScript syntax invalid"
[ -s "$HOST_TEST" ] || fail "standalone Activity-entry parser host test is missing"
grep -Fq 'SQL 文本' "$ACTIVITY" || fail "event view does not explain content redaction"
grep -Fq 'private void showMonitorEvents()' "$ACTIVITY" || fail "event filtering UI is missing"
grep -Fq 'matched > shown' "$ACTIVITY" || fail "event view has no render-row cap"
grep -Fq 'private int monitorEventGeneration;' "$ACTIVITY" || fail "event requests have no generation guard"
grep -Fq 'final String requestedPackage = targetPackage;' "$ACTIVITY" || fail "event reader does not snapshot the requested target"
grep -Fq '!requestedPackage.equals(targetPackage)' "$ACTIVITY" || fail "late event results can be shown for a newly selected target"
grep -Fq 'monitorEventGeneration++;' "$ACTIVITY" || fail "target changes and Activity teardown do not invalidate stale event reads"
if ! command -v javac >/dev/null 2>&1 || ! command -v java >/dev/null 2>&1; then
    fail "JDK is required to execute the standalone monitor parser regression"
fi
OUT=$(mktemp -d)
trap 'rm -rf "$OUT"' EXIT HUP INT TERM
javac -Xlint:all -Werror -d "$OUT" "$PARSER" "$HOST_TEST"
java -cp "$OUT" de.privacyguard.adhook.imported.dia.FxDiaMonitorEventParserHostTest
echo "PASS: Dia monitor-event browser is bounded, filterable and metadata-only"
