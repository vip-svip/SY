#!/bin/sh
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
DEX="$ROOT/adhook/app/src/main/java/de/privacyguard/adhook/imported/dia/FxDiaDexBrowserActivity.java"
INDEX="$ROOT/adhook/app/src/main/java/de/privacyguard/adhook/imported/dia/FxDiaDexIndex.java"
fail(){ echo "FAIL: $*" >&2; exit 1; }
[ -s "$DEX" ] && [ -s "$INDEX" ] || fail "Dia DEX browser sources missing"
grep -Fq 'REQUEST_DEX_DOCUMENT' "$DEX" || fail "standalone DEX document picker missing"
grep -Fq 'Intent.ACTION_OPEN_DOCUMENT' "$DEX" || fail "DEX selection must use Android document picker"
grep -Fq 'FxDiaDexIndex.readDex(input,' "$DEX" || fail "selected DEX is not parsed by the bounded parser"
grep -Fq 'selected = null;' "$DEX" || fail "standalone file must clear stale target app selection"
grep -Fq 'takePersistableUriPermission(' "$DEX" || fail "DEX picker must persist read permission when provider grants it"
grep -Fq 'releasePersistableUriPermission(' "$DEX" || fail "DEX URI permission must be released when the page finishes or source changes"
grep -Fq 'STATE_SOURCE_KIND' "$DEX" || fail "DEX source kind is not saved across Activity recreation"
grep -Fq 'STATE_TARGET_PACKAGE' "$DEX" || fail "selected APK package is not saved across Activity recreation"
grep -Fq 'STATE_DOCUMENT_URI' "$DEX" || fail "standalone DEX document URI is not saved across Activity recreation"
grep -Fq 'STATE_DOCUMENT_PERSISTED' "$DEX" || fail "persistable SAF grant state is not saved"
grep -Fq 'STATE_QUERY' "$DEX" || fail "DEX search query is not saved across Activity recreation"
grep -Fq 'STATE_SCROLL_Y' "$DEX" || fail "DEX results scroll position is not saved across Activity recreation"
grep -Fq 'restoreSourceAfterRecreation(state)' "$DEX" || fail "DEX source is not reloaded after Activity recreation"
grep -Fq 'loadDexDocument(documentUri, documentName)' "$DEX" || fail "restored standalone DEX URI is not re-parsed"
grep -Fq 'loadFrameworkDex();' "$DEX" || fail "Framework DEX source is not restored"
grep -Fq 'loadDex();' "$DEX" || fail "selected APK DEX source is not restored"
grep -Fq 'restoreResultScrollAfterRender();' "$DEX" || fail "result scroll position is not restored after asynchronous parsing"
grep -Fq 'if ("none".equals(sourceKind) || "installed-selected".equals(sourceKind))' "$DEX" || fail "late app inventory callback can overwrite active DEX source status"
grep -Fq 'resetResultScrollRestoration();' "$DEX" || fail "switching query/source must discard stale result scroll position"
grep -Fq 'expected == resultScroll' "$DEX" || fail "stale scroll callback must not mutate a newer page"
grep -Fq 'onSaveInstanceState(Bundle outState)' "$DEX" || fail "DEX browser state saving override missing"
grep -Fq 'if (!isChangingConfigurations()) releaseDocumentPermission();' "$DEX" || fail "persisted DEX URI grant must be released on final exit but retained during recreation"
! grep -Eq 'outState\.(putSerializable|putParcelableArrayList)\(".*(classes|dex)' "$DEX" || fail "large DEX index must not be written into Activity Bundle"
grep -Fq 'MAX_DEX_BYTES = 96 * 1024 * 1024' "$INDEX" || fail "DEX parser size cap is missing"
! grep -Eq 'DexClassLoader|PathClassLoader|loadClass\(' "$DEX" || fail "DEX browser must remain read-only"
echo "PASS: Dia standalone DEX file browser uses SAF and bounded read-only parsing"
